// Helper to normalize Arabic text for resilient searching
export function normalizeArabicText(str = '') {
  if (!str) return '';
  return str
    .toLowerCase()
    .trim()
    .replace(/[أإآءئؤ]/g, 'ا')
    .replace(/[ة]/g, 'ه')
    .replace(/[ى]/g, 'ي')
    .replace(/[\u064B-\u065F\u0670]/g, '') // remove tashkeel/diacritics
    .replace(/[\s\-_]+/g, ' ');
}

